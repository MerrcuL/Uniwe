  String get(String key) {
    return _localizedValues[locale.languageCode]?[key] ??
        _localizedValues['en']?[key] ??
        key;
  }

  /// "in 5 min" / "in 5 Min"
  String inMinutes(int minutes) =>
      isGerman ? 'in $minutes Min' : 'in $minutes min';

  /// "today" / "tomorrow" / "in 12 days"
  String inDays(int days) {
    if (days <= 0) return isGerman ? 'heute' : 'today';
    if (days == 1) return isGerman ? 'morgen' : 'tomorrow';
    return isGerman ? 'in $days Tagen' : 'in $days days';
  }

  /// Every key defined for [languageCode]; used by tests to keep the
  /// translations in sync.
  @visibleForTesting
  static Set<String> keysFor(String languageCode) =>
      _localizedValues[languageCode]?.keys.toSet() ?? const {};
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => ['en', 'de'].contains(locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) {
    return SynchronousFuture<AppLocalizations>(AppLocalizations(locale));
  }

  @override
  bool shouldReload(AppLocalizationsDelegate old) => false;
}
